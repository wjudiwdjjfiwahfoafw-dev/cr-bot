#!/usr/bin/env python3
"""Audit ``assets/unit_sprites``: which faction does each reference frame depict?

Read-only by default.  It writes two artefacts next to the sprites and never deletes a frame:

    assets/unit_sprites/_factions.json        machine-readable, consumed by the library
    assets/unit_sprites/_library_report.md    human-readable summary

Why you would run this
----------------------
The sprite library holds real in-game frames harvested from an asset dump that keeps **both team
tints** per character.  A folder that alternates red and blue renders is expected, not corrupt —
but it means one half of the library cannot be used to recognise units of the other side, and
most cards end up with only one tint.  See ``cr_bot/vision/sprite_factions.py`` for the
measurement and ``scripts/fetch_game_sprites.py --balance-factions`` for the fix.

Usage::

    python3 tools/sanitize_sprite_library.py                 # audit + write both artefacts
    python3 tools/sanitize_sprite_library.py --probe-upstream # show that the dump really is mixed
    python3 tools/sanitize_sprite_library.py --quarantine     # move minority-faction frames aside

``--quarantine`` is opt-in and non-destructive: frames move to
``assets/unit_sprites/_faction_quarantine/<card>/``.  Prefer ``--balance-factions`` on the fetch
script, which *adds* the missing faction instead of throwing half the frames away.
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
import sys
import urllib.request
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import cv2
import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from cr_bot.vision.sprite_factions import (  # noqa: E402  (after sys.path setup)
    ALLY,
    DECISIVE,
    ENEMY,
    NEUTRAL,
    CardFactions,
    audit_library,
    frame_faction,
    write_faction_map,
)

SPRITES = REPO_ROOT / "assets" / "unit_sprites"
QUARANTINE = SPRITES / "_faction_quarantine"


def duplicate_frames(card_dir: Path) -> List[List[str]]:
    """Byte-identical frames inside one folder (a symptom of one source directory → two cards)."""
    buckets: Dict[str, List[str]] = {}
    for path in sorted(card_dir.glob("*.png")):
        buckets.setdefault(hashlib.md5(path.read_bytes()).hexdigest(), []).append(path.name)
    return [v for v in buckets.values() if len(v) > 1]


def write_report(sprites: Path, audits: Sequence[CardFactions], db_cards: Sequence[str]) -> Path:
    mixed = [a for a in audits if a.is_mixed]
    one_sided = [a for a in audits if a.missing]
    no_tint = [a for a in audits if not a.enemy and not a.ally]
    missing_cards = sorted(set(db_cards) - {a.card for a in audits})

    lines = [
        "# Sprite library report",
        "",
        f"Generated by `tools/sanitize_sprite_library.py` over `{sprites.relative_to(REPO_ROOT)}`.",
        "",
        "Each frame is classified from its own colours: `score = log((blue_px+1)/(red_px+1))`",
        "over hue-restricted team colours, so orange skin/wood/gold cannot vote.",
        f"Positive is the ally (blue) render, negative the enemy (red) render, "
        f"|score| < {DECISIVE} is `neutral`.",
        "",
        f"- card folders: **{len(audits)}**",
        f"- folders holding **both** tints (usable for either team): **{len(mixed)}**",
        f"- folders holding **only one** tint (half the game's units cannot be matched): "
        f"**{len(one_sided)}**",
        f"- folders with **no** measurable team colour: **{len(no_tint)}**",
        f"- cards in the card database with **no** sprite folder: **{len(missing_cards)}**",
        "",
        "## Folders holding both tints",
        "",
        "| card | ally frames | enemy frames | neutral |",
        "| --- | --- | --- | --- |",
    ]
    for audit in sorted(mixed, key=lambda a: a.card):
        lines.append(
            f"| `{audit.card}` | {', '.join(audit.ally) or '-'} | "
            f"{', '.join(audit.enemy) or '-'} | {len(audit.neutral)} |"
        )
    lines += ["", "## Folders holding only one tint", "",
              "| card | only | frames |", "| --- | --- | --- |"]
    for audit in one_sided:
        frames = audit.ally or audit.enemy
        lines.append(f"| `{audit.card}` | {audit.missing} missing → "
                     f"{'ally' if audit.ally else 'enemy'} only | {', '.join(frames)} |")
    lines += ["", "## No measurable team colour", ""]
    lines += [f"- `{a.card}`: {', '.join(a.neutral)}" for a in no_tint] or ["_(none)_"]
    lines += ["", "## Cards with no sprite folder", "",
              ", ".join(f"`{c}`" for c in missing_cards) or "_(none)_", "",
              "Spells have no body sprite and are not expected here; a missing *troop* is a real "
              "gap and is reported by `scripts/fetch_game_sprites.py` as well.", "",
              "## Duplicate frames inside the library", ""]
    dup_rows = []
    for audit in audits:
        dups = duplicate_frames(sprites / audit.card)
        if dups:
            dup_rows.append(f"- `{audit.card}`: " + "; ".join(", ".join(g) for g in dups))
    lines += dup_rows or ["_(none)_"]

    path = sprites / "_library_report.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def quarantine(sprites: Path, audits: Sequence[CardFactions], dry_run: bool) -> List[Path]:
    """Move minority-faction frames aside (never deletes). Prefer re-fetching with both tints."""
    moved: List[Path] = []
    for audit in audits:
        if not audit.is_mixed:
            continue
        majority_is_enemy = len(audit.enemy) >= len(audit.ally)
        drop = audit.ally if majority_is_enemy else audit.enemy
        for name in drop:
            src = sprites / audit.card / f"{name}.png"
            if not src.is_file():
                continue
            moved.append(src)
            if dry_run:
                continue
            target = QUARANTINE / audit.card
            target.mkdir(parents=True, exist_ok=True)
            shutil.move(str(src), str(target / src.name))
    return moved


def probe_upstream(samples: Optional[Sequence[Tuple[str, str, int]]] = None) -> int:
    """Show that the upstream dump mixes both factions in one character directory."""
    base = ("https://raw.githubusercontent.com/smlbiobot/cr-assets-png/master/"
            "assets/sc/{dir}/{stem}_sprite_{idx:03d}.png")
    samples = samples or [
        ("chr_rage_barbarian_out", "chr_rage_barbarian", 348),
        ("chr_knight_out", "chr_knight", 120),
        ("chr_golem_out", "chr_golem", 120),
    ]
    print("probing the upstream dump (sampling every 6th frame):")
    for directory, stem, count in samples:
        tally = {ALLY: 0, ENEMY: 0, NEUTRAL: 0}
        for idx in range(0, count, 6):
            url = base.format(dir=directory, stem=stem, idx=idx)
            try:
                data = urllib.request.urlopen(url, timeout=15).read()
            except Exception:
                continue
            img = cv2.imdecode(np.frombuffer(data, np.uint8), cv2.IMREAD_UNCHANGED)
            if img is None:
                continue
            if img.ndim == 3 and img.shape[2] == 3:
                img = cv2.cvtColor(img, cv2.COLOR_BGR2BGRA)
            tally[frame_faction(img).faction] += 1
        print(f"  {stem:<20} ally={tally[ALLY]:<3} enemy={tally[ENEMY]:<3} "
              f"neutral={tally[NEUTRAL]}")
    print("\nBoth tints exist upstream, so a mixed local folder is the fetch script's selection "
          "at work — not a corrupt download.")
    return 0


def load_db_cards() -> List[str]:
    try:
        from cr_bot.config.cards_db import CARDS_DB

        return sorted(CARDS_DB)
    except Exception:
        return []


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sprites", default=str(SPRITES))
    ap.add_argument("--quarantine", action="store_true",
                    help="move minority-faction frames to _faction_quarantine/")
    ap.add_argument("--dry-run", action="store_true", help="with --quarantine: move nothing")
    ap.add_argument("--probe-upstream", action="store_true")
    args = ap.parse_args(argv)

    sprites = Path(args.sprites)
    if not sprites.is_dir():
        print(f"! no sprite library at {sprites}")
        return 1

    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    audits = audit_library(sprites)
    faction_path = write_faction_map(sprites, audits, stamp)
    report_path = write_report(sprites, audits, load_db_cards())

    mixed = [a for a in audits if a.is_mixed]
    one_sided = [a for a in audits if a.missing]
    print(f"{len(audits)} card folders audited")
    print(f"  both tints    : {len(mixed)}")
    print(f"  one tint only : {len(one_sided)}  "
          f"(these cannot be matched against the other side)")
    print(f"  faction map   -> {faction_path.relative_to(REPO_ROOT)}")
    print(f"  report        -> {report_path.relative_to(REPO_ROOT)}")

    if args.quarantine:
        moved = quarantine(sprites, audits, dry_run=args.dry_run)
        verb = "would move" if args.dry_run else "moved"
        print(f"  {verb} {len(moved)} frame(s) to {QUARANTINE.relative_to(REPO_ROOT)}")
        if moved and not args.dry_run:
            audits = audit_library(sprites)
            write_faction_map(sprites, audits, stamp)
            write_report(sprites, audits, load_db_cards())
            print("  artefacts regenerated after the move")

    if args.probe_upstream:
        print()
        probe_upstream()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
